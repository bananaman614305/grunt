/**
 * The generated ground-truth Stop-hook script (ADR-019).
 *
 * `milo verify install` writes this to the harness config dir; the harness runs
 * it on turn-end. It is PUSH-not-pull (a hook the agent cannot skip, because an
 * agent skips a self-check exactly when it is confabulating) and FAIL-OPEN
 * (every path exits 0 unless a confident, opted-in block fires, so a hiccup
 * never stalls the agent). It needs a Milo endpoint and a Milo key -- NOT a
 * TypeSafe key -- because Milo holds Jev server-side and does the auditing.
 *
 * Self-contained (only Node builtins + global fetch) so it runs from any
 * harness without a package install. The warn-vs-block rule mirrors
 * `decideAction` in `./verdict.ts`; a test `node --check`s this string so a
 * generated script is always valid JS.
 */

export const HOOK_SCRIPT = `#!/usr/bin/env node
/*
 * Milo ground-truth verification Stop hook (ADR-019). Generated by
 * \`milo verify install\`. Push-not-pull, cross-family (Milo's Jev audits),
 * fail-open. Do not edit; re-run the installer to regenerate.
 */
import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const MAX_SESSION_BLOCKS = 2;

function readStdin() {
  try { return readFileSync(0, "utf8"); } catch { return ""; }
}
function gitProbe(args) {
  try {
    return execSync("git " + args, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"], maxBuffer: 8 * 1024 * 1024 });
  } catch { return ""; }
}
function assistantTextFrom(msg) {
  if (!msg) return "";
  if (typeof msg.content === "string") return msg.content;
  if (Array.isArray(msg.content)) return msg.content.map((c) => (c && c.text) || "").join("\\n");
  return "";
}

async function main() {
  const endpoint = (process.env.MILO_ENDPOINT || "").replace(/\\/+$/, "");
  const key = process.env.MILO_KEY || "";
  if (endpoint === "" || key === "") {
    process.stderr.write("[milo verify] set MILO_ENDPOINT and MILO_KEY to enable ground-truth checks\\n");
    return 0;
  }

  let input = {};
  try { input = JSON.parse(readStdin() || "{}"); } catch {}
  const sessionId = String(input.session_id || input.sessionId || "session");

  // The finished turn's assistant text: from the transcript when the harness
  // provides one, else any message field on the hook input.
  let turn = "";
  const transcriptPath = input.transcript_path || input.transcriptPath;
  if (transcriptPath && existsSync(transcriptPath)) {
    try {
      const lines = readFileSync(transcriptPath, "utf8").trim().split("\\n");
      for (let i = lines.length - 1; i >= 0; i--) {
        const ev = JSON.parse(lines[i]);
        const msg = ev.message || ev;
        if (msg && msg.role === "assistant") {
          const text = assistantTextFrom(msg);
          if (text.trim() !== "") { turn = text; break; }
        }
      }
    } catch {}
  }
  if (turn.trim() === "") turn = String(input.last_assistant_message || input.message || "");

  // Read-only git probes, taken right now: the ground truth that cannot lie.
  const git = {
    status: gitProbe("status --porcelain"),
    diff: gitProbe("diff"),
    numstat: gitProbe("diff --numstat"),
    log: gitProbe("log --oneline -n 10"),
  };

  // Receipts of what actually ran, if the harness recorded any.
  let receipts = [];
  const receiptsPath = join(process.cwd(), ".milo", "receipts.json");
  if (existsSync(receiptsPath)) {
    try { const r = JSON.parse(readFileSync(receiptsPath, "utf8")); if (Array.isArray(r)) receipts = r; } catch {}
  }

  // POST to Milo's /v1/verify with a MILO key (never a TypeSafe key).
  let res;
  try {
    const r = await fetch(endpoint + "/v1/verify", {
      method: "POST",
      headers: { "content-type": "application/json", authorization: "Bearer " + key },
      body: JSON.stringify({ turn, git, receipts }),
    });
    res = await r.json();
  } catch { return 0; }
  if (!res || typeof res !== "object") return 0;

  // Persist git-tracked case law for any demanded oracle, re-checked mechanically.
  try {
    if (Array.isArray(res.caseLaw) && res.caseLaw.length > 0) {
      const dir = join(process.cwd(), ".milo");
      mkdirSync(dir, { recursive: true });
      const lawPath = join(dir, "caselaw.json");
      let law = [];
      if (existsSync(lawPath)) { try { const p = JSON.parse(readFileSync(lawPath, "utf8")); if (Array.isArray(p)) law = p; } catch {} }
      const byId = new Map(law.map((e) => [e.id, e]));
      for (const e of res.caseLaw) if (e && e.id) byId.set(e.id, e);
      writeFileSync(lawPath, JSON.stringify([...byId.values()], null, 2) + "\\n");
    }
  } catch {}

  const summary = res.summary || {};
  const finding = {
    finding: summary.finding || "clean",
    blocking: res.blocking === true,
    line: summary.line || "",
    unavailable: res.unavailable === true,
  };
  if (finding.unavailable || finding.finding === "clean") return 0;

  // Per-session block counter so a block fires at most twice.
  const stateDir = join(process.cwd(), ".milo");
  const statePath = join(stateDir, "verify-blocks.json");
  let blocks = {};
  if (existsSync(statePath)) { try { blocks = JSON.parse(readFileSync(statePath, "utf8")) || {}; } catch {} }
  const used = Number(blocks[sessionId] || 0);

  const blockEnabled = /^(1|true|yes|on)$/i.test(process.env.MILO_VERIFY_BLOCK || "");
  const warning = "Milo ground-truth check: " + finding.line;
  const canBlock = blockEnabled && finding.blocking && used < MAX_SESSION_BLOCKS;

  if (canBlock) {
    try {
      mkdirSync(stateDir, { recursive: true });
      blocks[sessionId] = used + 1;
      writeFileSync(statePath, JSON.stringify(blocks));
    } catch {}
    process.stderr.write(warning + "\\nBlocking this turn (MILO_VERIFY_BLOCK is on). Address the contradicted claim, or continue past this notice.\\n");
    return 2; // Claude Code: a Stop hook exit 2 blocks and shows stderr to the model
  }
  process.stderr.write(warning + "\\n");
  return 0;
}

main().then((code) => process.exit(typeof code === "number" ? code : 0)).catch(() => process.exit(0));
`;

/** The hook script body to write for `milo verify install`. */
export function hookScript(): string {
  return HOOK_SCRIPT;
}
